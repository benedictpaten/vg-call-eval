"""Aggregate run directories into one comparison table.

Deliberately a pure function of the comparison output: it re-reads summary.tsv
and never re-runs vg or aardvark, so re-reporting is free and analysis can be
redone without recomputation.
"""

from __future__ import annotations

import argparse
import csv
import json
import statistics as st
from collections import defaultdict
from pathlib import Path

ARM_ORDER = ["poisson", "poisson-depthfix", "readlik-support", "readlik-nomismap", "readlik"]


def _summary_row(path: Path, comparison: str, vtype: str) -> dict | None:
    if not path.exists():
        return None
    for row in csv.DictReader(open(path), delimiter="\t"):
        if (row["comparison"], row["region_label"], row["filter"], row["variant_type"]) == (
            comparison, "ALL", "ALL", vtype,
        ):
            return row
    return None


def collect(run_dirs: list[Path]) -> list[dict]:
    """One record per (run, arm)."""
    records = []
    for run in run_dirs:
        manifest = run / "dataset" / "manifest.json"
        if not manifest.exists():
            continue
        params = json.loads(manifest.read_text())["params"]
        timings = {}
        results = run / "results.json"
        if results.exists():
            timings = {r["arm"]: r for r in json.loads(results.read_text())}
        truth_counts = {}
        tc = run / "dataset" / "truth_counts.json"
        if tc.exists():
            truth_counts = json.loads(tc.read_text())

        for arm_dir in sorted((run / "compare").glob("*")):
            if not arm_dir.is_dir():
                continue
            arm = arm_dir.name
            gt = _summary_row(arm_dir / "summary.tsv", "GT", "ALL")
            if gt is None:
                continue
            bp = _summary_row(arm_dir / "summary.tsv", "BASEPAIR", "ALL")
            per_type = {
                vt: _summary_row(arm_dir / "summary.tsv", "GT", vt)
                for vt in ("Snv", "Insertion", "Deletion")
            }
            records.append(
                {
                    "run": run.name,
                    "config": f"{int(params['ref_length'])//1000}kb/{params['depth']:g}x/{params['read_length']}bp",
                    "seed": params["seed"],
                    "arm": arm,
                    "truth_total": int(gt["truth_total"]),
                    "truth_variants": truth_counts,
                    "gt_recall": float(gt["metric_recall"]),
                    "gt_precision": float(gt["metric_precision"]),
                    "gt_f1": float(gt["metric_f1"]),
                    "bp_recall": float(bp["metric_recall"]) if bp else None,
                    "bp_precision": float(bp["metric_precision"]) if bp else None,
                    "bp_f1": float(bp["metric_f1"]) if bp else None,
                    "snv_recall": float(per_type["Snv"]["metric_recall"]) if per_type["Snv"] else None,
                    "ins_recall": float(per_type["Insertion"]["metric_recall"]) if per_type["Insertion"] else None,
                    "del_recall": float(per_type["Deletion"]["metric_recall"]) if per_type["Deletion"] else None,
                    "seconds": timings.get(arm, {}).get("seconds"),
                }
            )
    return records


def _agg(values: list[float | None]) -> str:
    vals = [v for v in values if v is not None]
    if not vals:
        return "-"
    if len(vals) == 1:
        return f"{vals[0]:.4f}"
    return f"{st.mean(vals):.4f}±{st.stdev(vals):.4f}"


def markdown(records: list[dict]) -> str:
    by_config: dict[str, list[dict]] = defaultdict(list)
    for r in records:
        by_config[r["config"]].append(r)

    lines = [
        "# Consolidated results",
        "",
        "Generated by `vgcalleval report`. **Tier 0: simulated reads mapped back to the graph they were",
        "simulated from, so absolute numbers are optimistic — these are caller-vs-caller comparisons.**",
        "Values are mean±sd across replicate seeds.",
        "",
    ]

    # Configs ordered by how discriminating they are (spread of GT F1 across arms).
    def spread(cfg: str) -> float:
        f1 = [r["gt_f1"] for r in by_config[cfg]]
        return max(f1) - min(f1) if len(f1) > 1 else 0.0

    for config in sorted(by_config, key=lambda c: -spread(c)):
        rows = by_config[config]
        seeds = sorted({r["seed"] for r in rows})
        truth = rows[0]["truth_variants"]
        truth_str = ", ".join(f"{k} {v}" for k, v in sorted(truth.items())) if truth else "?"
        disc = spread(config)
        note = ""
        if disc < 0.005:
            note = "  ⚠ **arms within 0.005 F1 — this config does not discriminate**"
        lines += [
            f"## {config}",
            "",
            f"{len(seeds)} seed(s): {seeds}. Truth: {rows[0]['truth_total']} variants ({truth_str}).{note}",
            "",
            "| Arm | GT recall | GT precision | GT F1 | SNV rec | INS rec | DEL rec | BP F1 | call s |",
            "|---|---|---|---|---|---|---|---|---|",
        ]
        by_arm: dict[str, list[dict]] = defaultdict(list)
        for r in rows:
            by_arm[r["arm"]].append(r)
        for arm in ARM_ORDER:
            if arm not in by_arm:
                continue
            g = by_arm[arm]
            secs = [r["seconds"] for r in g if r["seconds"] is not None]
            lines.append(
                "| `{}` | {} | {} | {} | {} | {} | {} | {} | {} |".format(
                    arm,
                    _agg([r["gt_recall"] for r in g]),
                    _agg([r["gt_precision"] for r in g]),
                    _agg([r["gt_f1"] for r in g]),
                    _agg([r["snv_recall"] for r in g]),
                    _agg([r["ins_recall"] for r in g]),
                    _agg([r["del_recall"] for r in g]),
                    _agg([r["bp_f1"] for r in g]),
                    f"{st.mean(secs):.1f}" if secs else "-",
                )
            )
        lines.append("")
    return "\n".join(lines)


def main(argv=None) -> None:
    p = argparse.ArgumentParser(prog="vgcalleval-report")
    p.add_argument("runs", nargs="+", help="run directories produced by `vgcalleval run`")
    p.add_argument("--out", default=None, help="write markdown here instead of stdout")
    args = p.parse_args(argv)

    records = collect([Path(r) for r in args.runs])
    if not records:
        raise SystemExit("no comparison results found in the given run directories")
    text = markdown(records)
    if args.out:
        Path(args.out).write_text(text)
        print(f"wrote {args.out} ({len(records)} arm-runs)")
    else:
        print(text)


if __name__ == "__main__":
    main()
